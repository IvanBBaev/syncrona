const nested = (depth: number): string => `${"<a>".repeat(depth)}x${"</a>".repeat(depth)}`;

describe("compileUiPageHtml()", () => {
  it.each(CASES)("compiles %j as the SDK does", (html, expected) => {
    if (typeof expected === "string") {
      expect(compileUiPageHtml(html)).toBe(expected);
    } else if ("error" in expected) {
      expect(() => compileUiPageHtml(html)).toThrow(expected.error);
      expect(() => compileUiPageHtml(html)).not.toThrow(UnsupportedHtml);
    } else {
      expect(() => compileUiPageHtml(html)).toThrow(new UnsupportedHtml(expected.unsupported));
    }
  });

  it("accepts the SDK's maximum nesting depth", () => {
    const html = compileUiPageHtml(nested(100));
    expect(html.startsWith("\n<a>\n  <a>\n    <a>")).toBe(true);
    expect(html).toHaveLength(20502);
  });

  it.each([101, 102])("rejects %i levels of nesting as the SDK does", (depth) => {
    expect(() => compileUiPageHtml(nested(depth))).toThrow("Maximum nested tags exceeded");
  });
});
