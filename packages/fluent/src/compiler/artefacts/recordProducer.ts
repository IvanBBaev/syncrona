const REDIRECT_URLS: Record<string, string> = {
  generatedRecord: "generated_record",
  catalogHomePage: "catalog_home",
};

const DEFAULT_SCRIPT = `/** This script is executed before the Record is generated
* \`current\`- GlideRecord produced by Record Producer
* Don't use \`current.update()\` or \`current.insert()\` as the record is generated by Record Producer
* Don't use \`current.setValue('sys_class_name', 'xxx')\` as this will trigger reparent flow and can cause data loss
* Avoid \`current.setAbortAction()\` and generate a separate record
* Use \`producer.var1\` to access variables
*/`;
const DEFAULT_POST_INSERT_SCRIPT = `/**
* This script is executed after the record is generated. 
* \`current\` Is the GlideRecord produced by Record Producer. Use \`current.update()\` to update the record
* To access the variables, use \`producer.var1\` where var1 is the name of the variable
* To access the Record Producer use \`cat_item\`
*/`;
const DEFAULT_SAVE_SCRIPT = `/**
* This script is executed at every step save in Catalog Builder. 
* This script is executed before \`Script\` is executed.
* \`current\` Is the GlideRecord produced by Record Producer. 
* To access the variables, use \`producer.var1\` where var1 is the name of the variable
* To access the Record Producer use \`cat_item\`
*/`;

/** A script field: the given text as CDATA, or the SDK's default comment as plain text. */
function script(o: Options, key: string, fallback: string): FieldValue {
  const value = o.get(key);
  if (value === undefined) return fallback;
  if (value.kind !== "string")
    o.error(`${o.call.api}(): '${key}' must be a string.`, value);
  return cdata(value.value);
}

interface TargetTable {
  /** table_name: the name, or a reference to the Table() record. */
  field: FieldValue;
  /** The Table() record, whose columns mapped variables must name. */
  record?: CompiledRecord;
}

function targetTable(o: Options, ctx: BuildContext): TargetTable {
  const value = o.get("table");
  if (value === undefined) o.error(`${o.call.api}(): 'table' is required.`);
  if (value.kind === "string") return { field: value.value };
  if (value.kind === "call") {
    const record = ctx.recordOf(value);
    if (record.table === "sys_db_object") {
      const name = String(record.fields.get("name"));
      return {
        field: ctx.factory.createReference(
          "sys_db_object",
          record.id.getValue(),
          { name },
        ),
        record,
      };
    }
  }
  return o.error(
    `${o.call.api}(): 'table' must be a table name or a Table().`,
    value,
  );
}

/** Every record of `record`'s tree. */
function flat(record: CompiledRecord): CompiledRecord[] {
  return [record, ...record.children.flatMap(flat)];
}

/**
 * The SDK's check of the variables that map to a field: each field belongs to
 * the Table() (when the producer targets one) and is mapped only once.
 * Reports the first problem and lets the build go on, as the SDK does.
 */
function validateMappedFields(
  ctx: BuildContext,
  entries: [string, FluentCall][],
  table: CompiledRecord | undefined,
): void {
  const columns = table
    ? flat(table)
        .filter((r) => r.table === "sys_dictionary")
        .map((r) => r.elementAttributes?.element)
        .filter((element): element is string => !!element)
    : [];
  const valid = columns.length > 0 ? new Set(columns) : undefined;
  const mapped = new Map<string, string>();
  for (const [name, call] of entries) {
    const [arg] = call.args;
    const props = arg?.kind === "object" ? arg.props : undefined;
    const mapToField = props?.get("mapToField");
    const field = props?.get("field");
    if (
      mapToField?.kind !== "boolean" ||
      !mapToField.value ||
      field?.kind !== "string" ||
      field.value === ""
    )
      continue;
    if (valid && !valid.has(field.value)) {
      ctx.report(
        "error",
        `RecordProducer variable '${name}': field '${field.value}' does not belong to the target table. Valid fields are: ${[...valid].join(", ")}.`,
        field.loc,
      );
      return;
    }
    const earlier = mapped.get(field.value);
    if (earlier) {
      ctx.report(
        "error",
        `RecordProducer variable '${name}': field '${field.value}' is already mapped by variable '${earlier}'. Each table field can only be mapped by one variable.`,
        field.loc,
      );
      return;
    }
    mapped.set(field.value, name);
  }
}

export const recordProducer: ArtefactSpec = {
  properties: [
    ...CATALOG_BASE_PROPERTIES.filter((key) => key !== "accessType"),
    "table",
    "script",
    "postInsertScript",
    "saveScript",
    "redirectUrl",
    "allowEdit",
    "canCancel",
    "saveOptions",
  ],
  build(o, ctx) {
    const entries = variableEntries(o) ?? [];
    const sets = attachedSets(o, ctx);
    validateCatalogItem(o, ctx, entries, sets, "RecordProducer");

    const table = targetTable(o, ctx);
    const redirect = o.get("redirectUrl");
    const record = ctx.factory.createRecord({
      table: "sc_cat_item_producer",
      source: o.call.loc,
      installCategory: o.installCategory,
      explicitId: o.explicitId(),
      fields: {
        ...catalogBaseFields(o, ctx),
        table_name: table.field,
        script: script(o, "script", DEFAULT_SCRIPT),
        post_insert_script: script(
          o,
          "postInsertScript",
          DEFAULT_POST_INSERT_SCRIPT,
        ),
        save_script: script(o, "saveScript", DEFAULT_SAVE_SCRIPT),
        redirect_url:
          (redirect?.kind === "string"
            ? lookup(REDIRECT_URLS, redirect.value)
            : undefined) ?? "generated_record",
        allow_edit: o.boolean("allowEdit") ?? false,
        can_cancel: o.boolean("canCancel") ?? false,
        save_options: o.string("saveOptions") ?? "",
      },
    });
    record.children.push(...catalogM2MRecords(o, ctx, record, sets));
    if (o.get("variables") !== undefined) {
      validateMappedFields(ctx, entries, table.record);
      // The SDK writes the `table` option's value, which for a Table() is an object: "[object Object]".
      const producerTable = table.record
        ? "[object Object]"
        : String(table.field);
      for (const variable of buildVariables(o, ctx, entries, {
        kind: "item",
        record,
        variableSets: sets.map(({ set }) => set),
      })) {
        variable.fields.set("record_producer_table", producerTable);
        record.children.push(variable);
      }
    }
    return record;
  },
};
